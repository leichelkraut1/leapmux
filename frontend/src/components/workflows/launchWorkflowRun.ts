import type { AgentInfo } from '~/generated/proto/leapmux/v1/agent_pb'
import type { AgentProfile, WorkflowTemplate } from '~/generated/proto/leapmux/v1/workflow_pb'
import type { RoleOverrideInit } from '~/stores/workflows'
import * as workerRpc from '~/api/workerRpc'
import { openAgentRequestOptions } from '~/components/chat/providers/registry'
import { WorkflowRunAction } from '~/generated/proto/leapmux/v1/workflow_pb'

export interface LaunchWorkflowInput {
  /** The Lead's computer, which becomes the run's coordinator. */
  coordinatorWorkerId: string
  template: WorkflowTemplate
  /** The profiles the template's roles reference, read from the library computer. */
  profiles: readonly AgentProfile[]
  overrides: readonly RoleOverrideInit[]
  name: string
  objective: string
  /** The project directory on the coordinator; a role with none works here. */
  projectDir: string
  baseBranch: string
  /** The workspace every agent's tab goes into. */
  workspaceId: string
  /**
   * Places the Lead's tab, as NewAgentDialog's success path does. Returns
   * false when placement was refused; the Lead still exists and still
   * attaches, so the run does not stall on a missing tab.
   */
  placeLeadTab: (agent: AgentInfo) => boolean
}

export interface LaunchedWorkflow {
  coordinatorWorkerId: string
  runId: string
  leadAgentId: string
  leadTabPlaced: boolean
}

/**
 * Launch a run. The order is the contract with the coordinator:
 *
 *   1. CreateWorkflowRun records a PENDING run and mints the Lead's binding;
 *   2. OpenAgent opens the Lead on the coordinator WITH that binding, which is
 *      what confines its control socket to the run;
 *   3. its tab is placed in the workspace;
 *   4. AttachWorkflowLead starts the run -- the engine then opens every other
 *      agent itself, on its own computer.
 *
 * A Lead that fails to open leaves the run PENDING with nobody to attach, so
 * the run is deleted rather than left in the list.
 */
export async function launchWorkflowRun(input: LaunchWorkflowInput): Promise<LaunchedWorkflow> {
  const worker = input.coordinatorWorkerId
  const created = await workerRpc.createWorkflowRun(worker, {
    template: input.template,
    profiles: [...input.profiles],
    overrides: [...input.overrides],
    name: input.name.trim(),
    objective: input.objective.trim(),
    workingDir: input.projectDir.trim(),
    baseBranch: input.baseBranch.trim(),
    workspaceId: input.workspaceId,
  })
  const run = created.run
  const binding = created.leadBinding
  const lead = created.leadRole?.agent
  if (!run || !binding || !lead)
    throw new Error('The coordinator did not return the run and its Lead.')

  let agent: AgentInfo | undefined
  try {
    const opened = await workerRpc.openAgent(worker, {
      agentProvider: lead.agentProvider,
      title: `${run.name}: Lead`,
      titleAutoGenerated: false,
      workerId: worker,
      workingDir: lead.workingDir || run.workingDir,
      options: { ...openAgentRequestOptions(lead.agentProvider).options, ...lead.options },
      workflow: binding,
    })
    agent = opened.agent
    if (!agent)
      throw new Error('The coordinator did not return the Lead agent.')
  }
  catch (err) {
    await workerRpc.controlWorkflowRun(worker, { runId: run.id, action: WorkflowRunAction.DELETE }).catch(() => {})
    throw err
  }

  const leadTabPlaced = input.placeLeadTab(agent)
  await workerRpc.attachWorkflowLead(worker, { runId: run.id, agentId: agent.id })
  return { coordinatorWorkerId: worker, runId: run.id, leadAgentId: agent.id, leadTabPlaced }
}
